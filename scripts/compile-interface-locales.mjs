import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { format, resolveConfig } from "prettier";

import { GENERATED_INTERFACE_TRANSLATIONS } from "../app/lib/interface-locales.generated.ts";
import { MANUAL_INTERFACE_TRANSLATIONS } from "../app/lib/interface-locales.manual.ts";

const projectRoot = path.resolve(import.meta.dirname, "..");
const outputDirectory = path.join(projectRoot, "app", "lib", "interface-locales.runtime");
const targetLocales = ["fr", "es", "ru", "ar", "ja", "ko"];
const prettierConfig = (await resolveConfig(path.join(outputDirectory, "catalog.generated.ts"))) ?? {};

function mergedCatalog(locale) {
  return Object.fromEntries(
    Object.entries({
      ...GENERATED_INTERFACE_TRANSLATIONS[locale],
      ...MANUAL_INTERFACE_TRANSLATIONS[locale],
    }).sort(([left], [right]) => left.localeCompare(right, "en")),
  );
}

async function serialize(locale) {
  return format(
    `// Generated by scripts/compile-interface-locales.mjs. Do not edit by hand.\n\nexport const INTERFACE_TRANSLATIONS = ${JSON.stringify(mergedCatalog(locale), null, 2)} as const;\n`,
    { ...prettierConfig, parser: "typescript" },
  );
}

if (process.argv.includes("--check")) {
  const stale = [];
  for (const locale of targetLocales) {
    const outputPath = path.join(outputDirectory, `${locale}.generated.ts`);
    const current = await readFile(outputPath, "utf8").catch(() => "");
    if (current !== (await serialize(locale))) stale.push(locale);
  }
  if (stale.length) {
    throw new Error(
      `Runtime interface locale modules are stale (${stale.join(", ")}). Run npm run locales:runtime:generate.`,
    );
  }
  console.log(`Runtime interface catalogs are current for ${targetLocales.length} on-demand locales.`);
} else {
  await mkdir(outputDirectory, { recursive: true });
  for (const locale of targetLocales) {
    await writeFile(path.join(outputDirectory, `${locale}.generated.ts`), await serialize(locale), "utf8");
  }
  console.log(`Wrote ${targetLocales.length} runtime interface catalogs to ${outputDirectory}.`);
}
