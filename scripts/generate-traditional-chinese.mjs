import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import OpenCC from "opencc-js/cn2t";

const projectRoot = path.resolve(import.meta.dirname, "..");
const appRoot = path.join(projectRoot, "app");
const outputPath = path.join(appRoot, "lib", "traditional-chinese.generated.ts");
const converter = OpenCC.Converter({ from: "cn", to: "twp" });

async function sourceFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(entries.map(async (entry) => {
    const target = path.join(directory, entry.name);
    if (entry.isDirectory()) return sourceFiles(target);
    return /\.(?:ts|tsx)$/u.test(entry.name) && target !== outputPath ? [target] : [];
  }));
  return nested.flat();
}

const segments = new Set();
for (const file of await sourceFiles(appRoot)) {
  const source = await readFile(file, "utf8");
  for (const match of source.matchAll(/[\u3400-\u9fff]+/gu)) segments.add(match[0]);
}

const mappings = [...segments]
  .map((source) => [source, converter(source)])
  .filter(([source, target]) => source !== target)
  .sort((left, right) => right[0].length - left[0].length || left[0].localeCompare(right[0], "en"));

const generated = `// Generated by scripts/generate-traditional-chinese.mjs. Do not edit by hand.\n\nexport const TRADITIONAL_CHINESE_SEGMENTS = ${JSON.stringify(mappings, null, 2)} as const;\n`;
if (process.argv.includes("--check")) {
  const existing = await readFile(outputPath, "utf8").catch(() => "");
  if (existing !== generated) {
    throw new Error("Traditional Chinese catalog is stale. Run npm run locales:generate and commit the generated file.");
  }
} else {
  await writeFile(outputPath, generated, "utf8");
}
